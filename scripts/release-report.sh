#!/usr/bin/env bash
# Reproduce the release validation report.
#
# Runs, inside the pinned container:
#   1. the full CTest suite,
#   2. the differential matrix (writes build/differential-report.json),
#   3. Aegis-Bench with the ground-truth replay and a negative control,
# and copies the machine-written artifacts into docs/reports/<name>/ together
# with a header explaining what they do and do not show.
#
# Usage: scripts/release-report.sh [output-name]
#
# This produces a *reproducibility* artifact, not an effectiveness claim: the
# adapters are offline test doubles, so the cost columns are n/a by
# construction. See docs/reports/README.md.

set -euo pipefail

NAME="${1:-harness-validation}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_ROOT/docs/reports/$NAME"
IMAGE="${AEGIS_IMAGE:-aegis-ir-dev}"

mkdir -p "$OUT"

run_in_container() {
  MSYS_NO_PATHCONV=1 docker run --rm -v "$REPO_ROOT:/src" -w /src "$IMAGE" bash -c "$1"
}

echo "== build + test suite ==" | tee "$OUT/ctest.log"
run_in_container '
set -e
cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DLLVM_DIR=/usr/lib/llvm-23/lib/cmake/llvm
cmake --build build -j
cd build && ctest --output-on-failure
' 2>&1 | tee -a "$OUT/ctest.log"

echo "== bench: ground-truth replay (positive control) =="
run_in_container "
cd tools/aegis-bench
python3 -m aegis_bench run --tasks-root ../../benchmarks/tasks-public \
  --adapter ground-truth --profile baseline \
  --artifact-cache /tmp/aegis-bench-artifacts \
  --out /src/docs/reports/$NAME/bench-ground-truth
" 2>&1 | tee "$OUT/bench-ground-truth.log"

echo "== bench: stub (negative control) =="
run_in_container "
cd tools/aegis-bench
python3 -m aegis_bench run --tasks-root ../../benchmarks/tasks-public \
  --adapter stub --profile baseline \
  --artifact-cache /tmp/aegis-bench-artifacts \
  --out /src/docs/reports/$NAME/bench-stub || true
" 2>&1 | tee "$OUT/bench-stub.log"

cp "$REPO_ROOT/build/differential-report.json" "$OUT/" 2>/dev/null || true

cat > "$OUT/README.md" <<EOF
# Report: $NAME

Generated by \`scripts/release-report.sh\`. Reproduce with:

\`\`\`bash
scripts/release-report.sh $NAME
\`\`\`

## What this shows

- the CTest suite passes in the pinned container (\`ctest.log\`);
- the differential matrix runs eight build profiles (levels 0/1/2/3) over the
  same corpus with zero output mismatches and zero sanitizer reports
  (\`differential-report.json\`, including \`.text\`/\`.data\` totals and p95
  wall time per profile);
- Aegis-Bench builds the public binary-recovery task's stripped baseline probe
  and scores a known-correct solution at 100% and a compiling-but-wrong one at
  ~0% (\`bench-ground-truth/\`, \`bench-stub/\`), which validates the grader end
  to end; CTest additionally builds the level-1/2/3 probes.

## What this does **not** show

- **No effectiveness claim.** The adapters are offline test doubles. No model
  was involved, so the token and tool-call columns are \`n/a\` by construction.
  Protection effectiveness against any attacker class is unmeasured and is
  not claimed anywhere in this repository.
- No performance claim. The fixture is synthetic and small; wall times are
  process-startup dominated. Treat them as a regression tripwire only.

Claims that do exist for this stage are in \`docs/claims-ledger.md\`, and each
one links back to an artifact in this directory.
EOF

echo
echo "artifacts written to $OUT"
find "$OUT" -maxdepth 2 -type f | sort
